create table if not exists public.notification_broadcasts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 80),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

alter table public.notification_broadcasts enable row level security;
drop policy if exists "Authenticated users can read broadcasts" on public.notification_broadcasts;
create policy "Authenticated users can read broadcasts" on public.notification_broadcasts for select to authenticated using (true);
revoke all on public.notification_broadcasts from anon, public;
grant select on public.notification_broadcasts to authenticated;

create or replace function public.admin_broadcast_notification(p_title text, p_message text)
returns bigint language plpgsql security definer set search_path = public, auth as $$
declare new_id bigint;
begin
  if auth.uid() is null or not public.is_battleforge_admin() then raise exception 'Admin access required'; end if;
  if p_title is null or char_length(trim(p_title)) < 1 or char_length(trim(p_title)) > 80 then raise exception 'Title must be between 1 and 80 characters'; end if;
  if p_message is null or char_length(trim(p_message)) < 1 or char_length(trim(p_message)) > 1000 then raise exception 'Message must be between 1 and 1000 characters'; end if;
  insert into public.notification_broadcasts(title, message, created_by) values (trim(p_title), trim(p_message), auth.uid()) returning id into new_id;
  return new_id;
end;
$$;
revoke all on function public.admin_broadcast_notification(text, text) from public, anon;
grant execute on function public.admin_broadcast_notification(text, text) to authenticated;
notify pgrst, 'reload schema';
