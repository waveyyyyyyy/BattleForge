-- BattleForge online accounts + tournament registration foundation.
-- This deliberately does not implement a real-money wallet or charge points.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default 'Player' check (char_length(display_name) between 1 and 24),
 created_at timestamptz not null default now()
);
create table if not exists public.tournaments (
 id bigint generated by default as identity primary key,
 title text not null,
 game_mode text not null check (game_mode in ('SOLO','DUO','SQUAD')),
 entry_points integer not null default 0 check (entry_points >= 0),
 prize_pool_points integer not null default 0 check (prize_pool_points >= 0),
 max_players integer not null check (max_players > 0),
 status text not null default 'open' check (status in ('open','full','closed')),
 starts_at timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.tournament_entries (
 id uuid primary key default gen_random_uuid(),
 tournament_id bigint not null references public.tournaments(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 in_game_name text not null check (char_length(in_game_name) between 2 and 24),
 created_at timestamptz not null default now(),
 unique (tournament_id,user_id)
);
alter table public.profiles enable row level security;
alter table public.tournaments enable row level security;
alter table public.tournament_entries enable row level security;
drop policy if exists "Players can read their own profile" on public.profiles;
create policy "Players can read their own profile" on public.profiles for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "Players can update their own profile" on public.profiles;
create policy "Players can update their own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
drop policy if exists "Anyone can view tournaments" on public.tournaments;
create policy "Anyone can view tournaments" on public.tournaments for select to anon, authenticated using (true);
drop policy if exists "Players can read their own entries" on public.tournament_entries;
create policy "Players can read their own entries" on public.tournament_entries for select to authenticated using ((select auth.uid()) = user_id);
revoke insert, update, delete on public.tournament_entries from anon, authenticated;
revoke insert, update, delete on public.tournaments from anon, authenticated;
create or replace function public.create_profile_for_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
 insert into public.profiles (id,display_name)
 values (new.id,coalesce(nullif(left(new.raw_user_meta_data ->> 'display_name',24),''),'Player'))
 on conflict (id) do nothing;
 return new;
end;
$$;
drop trigger if exists on_auth_user_created_battleforge on auth.users;
create trigger on_auth_user_created_battleforge after insert on auth.users for each row execute procedure public.create_profile_for_new_user();
create or replace function public.join_tournament(p_tournament_id bigint,p_in_game_name text)
returns uuid language plpgsql security definer set search_path = ''
as $$
declare
 v_user_id uuid := auth.uid();
 v_tournament public.tournaments%rowtype;
 v_entry_id uuid;
 v_count integer;
 v_name text := btrim(p_in_game_name);
begin
 if v_user_id is null then raise exception 'Sign in before joining a tournament'; end if;
 if v_name is null or char_length(v_name) < 2 or char_length(v_name) > 24 then raise exception 'In-game name must be between 2 and 24 characters'; end if;
 select * into v_tournament from public.tournaments where id = p_tournament_id for update;
 if not found then raise exception 'Tournament not found'; end if;
 if v_tournament.status <> 'open' then raise exception 'This tournament is not open for entries'; end if;
 select count(*)::integer into v_count from public.tournament_entries where tournament_id = p_tournament_id;
 if v_count >= v_tournament.max_players then
   update public.tournaments set status = 'full' where id = p_tournament_id;
   raise exception 'This tournament is full';
 end if;
 insert into public.tournament_entries (tournament_id,user_id,in_game_name) values (p_tournament_id,v_user_id,v_name) returning id into v_entry_id;
 select count(*)::integer into v_count from public.tournament_entries where tournament_id = p_tournament_id;
 if v_count >= v_tournament.max_players then update public.tournaments set status = 'full' where id = p_tournament_id; end if;
 return v_entry_id;
end;
$$;
revoke all on function public.join_tournament(bigint,text) from public;
grant execute on function public.join_tournament(bigint,text) to authenticated;
